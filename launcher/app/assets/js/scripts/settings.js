/**
 * Sistemi tarar; önerilen RAM'i uygular ve sonucu donanim.json olarak yazar.
 *
 * @returns {Promise.<Object>} Yazılan kayıt.
 */
async function hapiDonanimTara(){
    const ham = await ipcRenderer.invoke(HAPI_OPCODE.DONANIM_TARA)
    const kayit = HapiDonanim.donanimKaydi(ham)
    hapiDonanimLogger.info('Tarama sonucu', kayit)

    const serv = ConfigManager.getSelectedServer()
    ConfigManager.setMaxRAM(serv, `${kayit.javaRamMB}M`)
    ConfigManager.setMinRAM(serv, `${kayit.javaRamMB}M`)
    ConfigManager.save()

    const dosya = hapiDonanimDosyasi()
    hapiFs.ensureDirSync(path.dirname(dosya))
    hapiFs.writeFileSync(dosya, JSON.stringify(kayit, null, 2), 'utf-8')
    return kayit
}

/**
 * İlk açılışta (donanim.json yoksa) taramayı kendiliğinden yapar.
 */
async function hapiIlkDonanimTaramasi(){
    try {
        if(!hapiFs.existsSync(hapiDonanimDosyasi())){
            await hapiDonanimTara()
        }
    } catch(err) {
        hapiDonanimLogger.error('Donanım taraması başarısız.', err)
    }
}

/**
 * Son tarama sonucunu ayarlar ekranında gösterir.
 */
function hapiDonanimGoster(){
    let kayit = null
    try {
        kayit = JSON.parse(hapiFs.readFileSync(hapiDonanimDosyasi(), 'utf-8'))
    } catch(_err) {
        // Henüz taranmamış.
    }
    if(kayit == null){
        hapiDonanimOzet.innerHTML = Lang.queryEJS('settings.hardwareNotScanned')
        return
    }
    hapiDonanimOzet.innerHTML = Lang.queryJS('settings.hardware.summary', {
        cpu: kayit.cpu || '?',
        cekirdek: kayit.cekirdek,
        ram: (kayit.ramMB / 1024).toFixed(1),
        gpu: kayit.gpu || Lang.queryJS('settings.hardware.unknownGpu'),
        ekran: kayit.ekran || '?',
        profil: Lang.queryJS(`settings.hardware.profiles.${kayit.profil}`),
        javaRam: (kayit.javaRamMB / 1024).toFixed(1)
    })
}

