/**
 * Save the mod configuration based on the UI values.
 */
function saveModConfiguration(){
    const serv = ConfigManager.getSelectedServer()
    const modConf = ConfigManager.getModConfiguration(serv)
    modConf.mods = _saveModConfiguration(modConf.mods)
    ConfigManager.setModConfiguration(serv, modConf)
}

/**
 * Recursively save mod config with submods.
 * 
 * @param {Object} modConf Mod config object to save.
 */
function _saveModConfiguration(modConf){
    for(let m of Object.entries(modConf)){
        const tSwitch = settingsModsContainer.querySelectorAll(`[formod='${m[0]}']`)
        if(!tSwitch[0].hasAttribute('dropin')){
            if(typeof m[1] === 'boolean'){
                modConf[m[0]] = tSwitch[0].checked
            } else {
                if(m[1] != null){
                    if(tSwitch.length > 0){
                        modConf[m[0]].value = tSwitch[0].checked
                    }
                    modConf[m[0]].mods = _saveModConfiguration(modConf[m[0]].mods)
                }
            }
        }
    }
    return modConf
}

// Shader paketi klasörü yardımcıları (drop-in mod özelliği HapiClient'te kapalıdır).

const SHADER_REGEX = /^(.+)\.zip$/
const SHADER_OPTION = /shaderPack=(.+)/
const SHADER_DIR = 'shaderpacks'
const SHADER_CONFIG = 'optionsshaders.txt'

const ShaderpackUtil = {

    validateDir(dir){
        hapiFs.ensureDirSync(dir)
    },

    scanForShaderpacks(instanceDir){
        const shaderDir = path.join(instanceDir, SHADER_DIR)
        const packsDiscovered = [{
            fullName: 'OFF',
            name: Lang.queryJS('settings.shaderpacks.off')
        }]
        if(hapiFs.existsSync(shaderDir)){
            for(const file of hapiFs.readdirSync(shaderDir)){
                const match = SHADER_REGEX.exec(file)
                if(match != null){
                    packsDiscovered.push({
                        fullName: match[0],
                        name: match[1]
                    })
                }
            }
        }
        return packsDiscovered
    },

    getEnabledShaderpack(instanceDir){
        this.validateDir(instanceDir)
        const optionsShaders = path.join(instanceDir, SHADER_CONFIG)
        if(hapiFs.existsSync(optionsShaders)){
            const match = SHADER_OPTION.exec(hapiFs.readFileSync(optionsShaders, { encoding: 'utf-8' }))
            if(match != null){
                return match[1]
            }
        }
        return 'OFF'
    },

    setEnabledShaderpack(instanceDir, pack){
        this.validateDir(instanceDir)
        const optionsShaders = path.join(instanceDir, SHADER_CONFIG)
        let buf
        if(hapiFs.existsSync(optionsShaders)){
            buf = hapiFs.readFileSync(optionsShaders, { encoding: 'utf-8' })
            buf = buf.replace(SHADER_OPTION, `shaderPack=${pack}`)
        } else {
            buf = `shaderPack=${pack}`
        }
        hapiFs.writeFileSync(optionsShaders, buf, { encoding: 'utf-8' })
    },

    addShaderpacks(files, instanceDir){
        const p = path.join(instanceDir, SHADER_DIR)
        this.validateDir(p)
        for(const f of files){
            if(SHADER_REGEX.exec(f.name) != null){
                hapiFs.moveSync(f.path, path.join(p, f.name))
            }
        }
    }
}

